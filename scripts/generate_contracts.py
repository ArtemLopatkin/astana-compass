#!/usr/bin/env python3
"""Generate Python resource snapshots and TypeScript types from canonical root JSON."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "packages/contracts/src/astana_contracts/data"
TYPES = ROOT / "packages/api_client/src/generated.ts"
KEYWORDS = {
    "$schema", "$id", "$defs", "$ref", "title", "description", "type", "properties",
    "required", "additionalProperties", "items", "prefixItems", "enum", "const", "anyOf",
    "oneOf", "allOf", "if", "then", "else", "not", "minItems", "maxItems", "uniqueItems",
    "minimum", "maximum", "exclusiveMinimum", "minLength", "maxLength", "pattern", "format",
}
SCHEMA_CHILDREN = {"items", "additionalProperties", "if", "then", "else", "not"}
SCHEMA_LISTS = {"anyOf", "oneOf", "allOf", "prefixItems"}


def check_keywords(schema: dict | bool, definitions: dict) -> None:
    """Fail loudly for new schema constructs rather than silently generate wrong types."""
    if isinstance(schema, bool):
        return
    unsupported = schema.keys() - KEYWORDS
    if unsupported:
        raise ValueError(f"Generator does not recognize schema keywords: {sorted(unsupported)}")
    if "$ref" in schema:
        if not schema["$ref"].startswith("#/$defs/") or schema["$ref"].split("/")[-1] not in definitions:
            raise ValueError("Only valid local $defs references can be generated")
    for key, value in schema.items():
        if key in ("properties", "$defs"):
            for child in value.values():
                check_keywords(child, definitions)
        elif key in SCHEMA_CHILDREN:
            check_keywords(value, definitions)
        elif key in SCHEMA_LISTS:
            for child in value:
                check_keywords(child, definitions)


def literal(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def union(parts: list[str]) -> str:
    return " | ".join(dict.fromkeys(parts))


def ts_type(schema: dict | bool) -> str:
    if isinstance(schema, bool):
        return "unknown" if schema else "never"
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return literal(schema["const"])
    if "enum" in schema:
        return union([literal(value) for value in schema["enum"]])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return union([ts_type(child) for child in schema[key]])
    kind = schema.get("type")
    if isinstance(kind, list):
        return union([ts_type({**schema, "type": entry}) for entry in kind])
    if kind == "object" or "properties" in schema:
        required = set(schema.get("required", []))
        props = [f"  {literal(name)}{'' if name in required else '?'}: {ts_type(value)};"
                 for name, value in schema.get("properties", {}).items()]
        if schema.get("additionalProperties") not in (False, None):
            props.append(f"  [key: string]: {ts_type(schema['additionalProperties'])};")
        return "{\n" + "\n".join(props) + "\n}"
    if kind == "array":
        prefix = schema.get("prefixItems")
        if prefix and schema.get("minItems") == schema.get("maxItems") == len(prefix):
            return "[" + ", ".join(ts_type(item) for item in prefix) + "]"
        return f"Array<{ts_type(schema.get('items', True))}>"
    if kind in ("number", "integer"):
        return "number"
    if kind in ("string", "boolean", "null"):
        return kind
    # Structural conditional fragments are traversed/recognized but validation
    # predicates (if/then/else/not) remain authoritative only in JSON Schema.
    if "allOf" in schema:
        structural = [child for child in schema["allOf"] if "if" not in child and "not" not in child]
        return " & ".join(f"({ts_type(child)})" for child in structural) or "unknown"
    return "unknown"


def outputs() -> dict[Path, bytes]:
    schema_bytes = (ROOT / "contracts.schema.json").read_bytes()
    examples_bytes = (ROOT / "contracts.examples.json").read_bytes()
    schema = json.loads(schema_bytes)
    definitions = schema["$defs"]
    check_keywords(schema, definitions)
    for name in definitions:
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
            raise ValueError("A schema definition is not a valid TypeScript identifier")
    digest = hashlib.sha256(schema_bytes).hexdigest()
    header = f'''// AUTO-GENERATED by scripts/generate_contracts.py. Do not edit.\n// Canonical schema SHA-256: {digest}\n// Structural types are weaker than JSON Schema: numeric/string bounds, formats,\n// uniqueness, exact object keys, if/then/else/not predicates and cross-reference\n// invariants require server runtime validation. All schema keywords are checked.\n\n'''
    body = "\n\n".join(f"export type {name} = {ts_type(value)};" for name, value in definitions.items()) + "\n"
    manifest = {"generated_by": "scripts/generate_contracts.py", "do_not_edit": True,
                "schema_sha256": digest, "examples_sha256": hashlib.sha256(examples_bytes).hexdigest()}
    return {
        DATA / "contracts.schema.json": schema_bytes,
        DATA / "contracts.examples.json": examples_bytes,
        DATA / "generated.json": (json.dumps(manifest, indent=2) + "\n").encode(),
        TYPES: (header + body).encode(),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files differ; do not write")
    args = parser.parse_args()
    stale = []
    generated = outputs()
    for path, expected in generated.items():
        if args.check:
            if not path.exists() or path.read_bytes() != expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
    if stale:
        raise SystemExit("Generated contract files are stale:\n" + "\n".join(stale))
    print(f"{'Verified' if args.check else 'Generated'} {len(generated)} contract artifacts.")


if __name__ == "__main__":
    main()
